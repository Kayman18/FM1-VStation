"""Portable format fixture checks; generates the complete current Init snapshot."""
import pathlib,struct,zlib
root=pathlib.Path(__file__).resolve().parents[1]
import re
text=(root/'engine/synth.c').read_text()
values=list(map(int,re.search(r'synth_defaults\[SYNTH_PARAM_COUNT\]=\{([^}]+)',text)[1].split(',')))
assert len(values)==170 and max(values)<=255
payload=b'FVS1'+bytes([1,len(values),0,0])+bytes(values)
record=payload+struct.pack('<I',zlib.crc32(payload))
assert len(record)==182
out=root/'research/factory-presets/fm1-init.fvspreset';out.write_bytes(record)
assert zlib.crc32(record[:-4])==struct.unpack('<I',record[-4:])[0]
(root/'app/preset_catalog.h').write_text('/* Complete FM1 init snapshot; generated by tests/preset_validation_test.py. */\nstatic const uint8_t init_preset[PRESET_BYTES]={'+','.join(map(str,record))+'};\n')
print('Complete 170-control init fixture and embedded catalog generated')
